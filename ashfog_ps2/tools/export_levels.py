#!/usr/bin/env python3
"""Выгружает карты ASHFOG (../ashfog/levels) в src/levels_data.h для PS2-порта."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'ashfog'))
from levels import hospital, city, cemetery

ORDER = [('hospital', hospital), ('city', city), ('cemetery', cemetery)]
out = ['/* AUTO-GENERATED by tools/export_levels.py - do not edit */', '#pragma once', '#include "game.h"', '']
names = []
for name, mod in ORDER:
    lv = mod.build()
    grid, spots = lv['grid'], lv.get('spots', {})
    H, W = len(grid), len(grid[0])
    items = list(lv.get('items', []))
    rows = []
    for r, row in enumerate(grid):
        row2 = ''
        for c, ch in enumerate(row):
            if ch in spots:               # цифры-предметы -> список items
                items.append((c, r, spots[ch])); ch = '.'
            row2 += ch
        rows.append(row2)
    out.append(f'static const char *const lv_{name}_grid[{H}] = {{')
    for row in rows:
        out.append('  "' + row.replace('\\', '\\\\').replace('"', '\\"') + '",')
    out.append('};')
    out.append(f'static const ItemSpawn lv_{name}_items[] = {{')
    for c, r, i in items: out.append(f'  {{{c}, {r}, "{i}"}},')
    out.append('  {-1, -1, 0}\n};')
    locks = lv.get('locks', {}); exits = lv.get('exits', {})
    out.append(f'static const LockDef lv_{name}_locks[] = {{')
    for k, v in locks.items(): out.append(f"  {{'{k}', \"{v}\"}},")
    out.append("  {0, 0}\n};")
    out.append(f'static const ExitDef lv_{name}_exits[] = {{')
    for k, (nxt, key) in exits.items(): out.append(f"  {{'{k}', \"{nxt}\", \"{key}\"}},")
    out.append("  {0, 0, 0}\n};")
    fog = lv['fog']
    ind = lv.get('indoor')
    if ind is None: indref = 'NULL'
    else:
        out.append(f'static const char *const lv_{name}_indoor[{H}] = {{')
        for r in range(H):
            out.append('  "' + ''.join('1' if (c, r) in ind else '0' for c in range(W)) + '",')
        out.append('};'); indref = f'lv_{name}_indoor'
    out.append(f'static const LevelDef LV_{name.upper()} = {{"{name}", {W}, {H}, lv_{name}_grid, lv_{name}_items, lv_{name}_locks, lv_{name}_exits, '
               f'{lv["h"]}f, {1 if lv["dark"] else 0}, {{{fog[0][0]}, {fog[0][1]}, {fog[0][2]}}}, {fog[1][0]:.1f}f, {fog[1][1]:.1f}f, {indref}}};')
    out.append('')
    names.append(name)
    nen = sum(row.count(ch) for row in rows for ch in 'wzNY')
    print(f'{name}: {W}x{H}, items={len(items)}, enemies={nen}')
out.append('static const LevelDef *const ALL_LEVELS[] = {' + ', '.join(f'&LV_{n.upper()}' for n in names) + '};')
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'levels_data.h'), 'w').write('\n'.join(out) + '\n')
